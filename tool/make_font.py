"""Bakes DejaVu Sans into src/font_data.h: each character's advance, which
the renderer lays out its plot with, and its anti-aliased bitmap, which the
Picture output draws its text from.

A viewer of the plot data draws the texts in a font of the same size. The
pictures need no font library and no system fonts, which Android and a frozen
desktop backend do not share. The size is the reference renderer's, 16
pixels. Run it again only to change the size or the characters:

    python tool/make_font.py

It needs Pillow.
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SIZE = 16

# ASCII, Latin-1, Latin Extended-A (č, š, ž and the rest of Central Europe's
# letters), Greek (Ω, µ's neighbours, Δ) and a few symbols units use.
CHARACTERS = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + list(range(0x100, 0x180))
    + list(range(0x391, 0x3CA))
    + [0x2013, 0x2014, 0x2022, 0x2026, 0x2030, 0x2032, 0x2033, 0x2103, 0x2109, 0x2126, 0x2212, 0x221A, 0x221E]
)


def bake(path: Path, name: str) -> tuple[str, list[str], int, int]:
    font = ImageFont.truetype(str(path), SIZE)
    ascent, descent = font.getmetrics()
    pixels: list[int] = []
    glyphs: list[str] = []
    for code in CHARACTERS:
        char = chr(code)
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = max(0, right - left), max(0, bottom - top)
        advance = round(font.getlength(char) * 64)
        offset = len(pixels)
        if width and height:
            image = Image.new("L", (width, height), 0)
            ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor="ls")
            pixels.extend(image.tobytes())
        glyphs.append(f"    {{0x{code:04X}, {left}, {top}, {width}, {height}, {advance}, {offset}}},")
    rows = [", ".join(str(p) for p in pixels[i : i + 32]) for i in range(0, len(pixels), 32)]
    data = f"static const uint8_t k{name}Pixels[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"
    return data, glyphs, ascent, descent


def main() -> None:
    parts = [
        "// Generated by tool/make_font.py from DejaVu Sans. Do not edit.",
        "//",
        "// DejaVu Sans is (c) Bitstream, under the Bitstream Vera license in",
        "// fonts/bitstream-vera-license.txt; DejaVu's changes are in the public domain.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace daq::modules::universal_renderer::font",
        "{",
        "",
        "/// One character: its code point, the offset of its bitmap from the pen on",
        "/// the baseline, its size, its advance in 1/64 pixels, and where its pixels",
        "/// start.",
        "struct Glyph",
        "{",
        "    uint32_t code;",
        "    int8_t left;",
        "    int8_t top;",
        "    uint8_t width;",
        "    uint8_t height;",
        "    uint16_t advance;",
        "    uint32_t offset;",
        "};",
        "",
        f"constexpr int kSize = {SIZE};",
        "",
    ]
    for file, name in (("DejaVuSans.ttf", "Regular"), ("DejaVuSans-Bold.ttf", "Bold")):
        data, glyphs, ascent, descent = bake(ROOT / "fonts" / file, name)
        parts.append(f"constexpr int k{name}Ascent = {ascent};")
        parts.append(f"constexpr int k{name}Descent = {descent};")
        parts.append(data)
        parts.append(f"static const Glyph k{name}Glyphs[] = {{")
        parts.extend(glyphs)
        parts.append("};")
        parts.append("")
    parts.append("}  // namespace daq::modules::universal_renderer::font")
    (ROOT / "src" / "font_data.h").write_text("\n".join(parts) + "\n")
    print(f"wrote src/font_data.h with {len(CHARACTERS)} characters in two weights")


if __name__ == "__main__":
    main()
